// Command docs regenerates docs/reference/ from the CRDs, the binaries' --help output and the
// Helm chart's values.yaml. Run it from the repository root: make docs-reference.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"sigs.k8s.io/yaml"
	yamlv3 "sigs.k8s.io/yaml/goyaml.v3"
)

const (
	outDir = "docs/reference"
	notice = "<!-- generated by `make docs-reference`; do not edit -->"
)

func main() {
	pages := []struct {
		file string
		gen  func() (string, error)
	}{
		{"custom-resources.md", customResources},
		{"operator-flags.md", operatorFlags},
		{"agent-flags.md", agentFlags},
		{"chart-values.md", chartValues},
	}
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		fail(err)
	}
	for _, p := range pages {
		body, err := p.gen()
		if err != nil {
			fail(fmt.Errorf("%s: %w", p.file, err))
		}
		if err := os.WriteFile(filepath.Join(outDir, p.file), []byte(body), 0o644); err != nil {
			fail(err)
		}
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}

func header(title, summary string) *strings.Builder {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n%s\n\n%s\n", title, summary, notice)
	return &b
}

func cell(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	return strings.ReplaceAll(s, "|", `\|`)
}

func code(s string) string {
	if s == "" {
		return ""
	}
	return "`" + cell(s) + "`"
}

func row(b *strings.Builder, cells ...string) {
	fmt.Fprintf(b, "| %s |\n", strings.Join(cells, " | "))
}

func tableHead(b *strings.Builder, cols ...string) {
	b.WriteString("\n")
	row(b, cols...)
	seps := make([]string, len(cols))
	for i := range seps {
		seps[i] = "---"
	}
	row(b, seps...)
}

// Custom resources

type schema struct {
	Type                 string                     `json:"type"`
	Format               string                     `json:"format"`
	Description          string                     `json:"description"`
	Properties           map[string]*schema         `json:"properties"`
	Items                *schema                    `json:"items"`
	AdditionalProperties *schema                    `json:"additionalProperties"`
	Required             []string                   `json:"required"`
	Default              any                        `json:"default"`
	Enum                 []any                      `json:"enum"`
	Pattern              string                     `json:"pattern"`
	Minimum              *float64                   `json:"minimum"`
	Maximum              *float64                   `json:"maximum"`
	MinLength            *int64                     `json:"minLength"`
	MaxLength            *int64                     `json:"maxLength"`
	MinItems             *int64                     `json:"minItems"`
	MaxItems             *int64                     `json:"maxItems"`
	IntOrString          bool                       `json:"x-kubernetes-int-or-string"`
	Validations          []struct{ Message string } `json:"x-kubernetes-validations"`
	_                    map[string]json.RawMessage `json:"-"`
}

type crd struct {
	Spec struct {
		Group string `json:"group"`
		Names struct {
			Kind       string   `json:"kind"`
			Plural     string   `json:"plural"`
			ShortNames []string `json:"shortNames"`
		} `json:"names"`
		Scope    string `json:"scope"`
		Versions []struct {
			Name   string `json:"name"`
			Schema struct {
				OpenAPIV3Schema *schema `json:"openAPIV3Schema"`
			} `json:"schema"`
		} `json:"versions"`
	} `json:"spec"`
}

func customResources() (string, error) {
	files, err := filepath.Glob("config/crd/bases/*.yaml")
	if err != nil {
		return "", err
	}
	crds := make([]crd, 0, len(files))
	for _, f := range files {
		data, err := os.ReadFile(f)
		if err != nil {
			return "", err
		}
		var c crd
		if err := yaml.Unmarshal(data, &c); err != nil {
			return "", fmt.Errorf("%s: %w", f, err)
		}
		crds = append(crds, c)
	}
	sort.Slice(crds, func(i, j int) bool { return crds[i].Spec.Names.Kind < crds[j].Spec.Names.Kind })

	b := header("Custom resources",
		"Every field of every custom resource Protem defines, with its type, whether it is required, its default, "+
			"allowed values and constraints. Generated from the CRDs in config/crd/bases.")
	for _, c := range crds {
		for _, v := range c.Spec.Versions {
			root := v.Schema.OpenAPIV3Schema
			fmt.Fprintf(b, "\n## %s\n\n", c.Spec.Names.Kind)
			fmt.Fprintf(b, "- API version: `%s/%s`\n", c.Spec.Group, v.Name)
			fmt.Fprintf(b, "- Scope: %s\n", c.Spec.Scope)
			names := append([]string{c.Spec.Names.Plural}, c.Spec.Names.ShortNames...)
			fmt.Fprintf(b, "- Resource names: `%s`\n", strings.Join(names, "`, `"))
			if root.Description != "" {
				fmt.Fprintf(b, "\n%s\n", strings.Join(strings.Fields(root.Description), " "))
			}
			tableHead(b, "Field", "Type", "Required", "Default", "Enum", "Constraints", "Description")
			for _, top := range []string{"spec", "status"} {
				if s, ok := root.Properties[top]; ok {
					walk(b, top, s, contains(root.Required, top))
				}
			}
		}
	}
	return b.String(), nil
}

func walk(b *strings.Builder, path string, s *schema, required bool) {
	req := "no"
	if required {
		req = "yes"
	}
	var def string
	if s.Default != nil {
		def = code(jsonString(s.Default))
	}
	enum := make([]string, len(s.Enum))
	for i, e := range s.Enum {
		enum[i] = code(jsonString(e))
	}
	row(b, code(path), cell(typeOf(s)), req, def, strings.Join(enum, ", "), cell(constraints(s)), cell(s.Description))

	for _, name := range sortedKeys(s.Properties) {
		walk(b, path+"."+name, s.Properties[name], contains(s.Required, name))
	}
	if s.Items != nil && len(s.Items.Properties) > 0 {
		for _, name := range sortedKeys(s.Items.Properties) {
			walk(b, path+"[]."+name, s.Items.Properties[name], contains(s.Items.Required, name))
		}
	}
	if s.AdditionalProperties != nil && len(s.AdditionalProperties.Properties) > 0 {
		for _, name := range sortedKeys(s.AdditionalProperties.Properties) {
			walk(b, path+".*."+name, s.AdditionalProperties.Properties[name], contains(s.AdditionalProperties.Required, name))
		}
	}
}

func typeOf(s *schema) string {
	switch {
	case s.IntOrString:
		return "int-or-string"
	case s.Type == "array" && s.Items != nil:
		return "[]" + typeOf(s.Items)
	case s.Type == "object" && s.AdditionalProperties != nil:
		return "map[string]" + typeOf(s.AdditionalProperties)
	case s.Format != "":
		return s.Type + " (" + s.Format + ")"
	}
	return s.Type
}

func constraints(s *schema) string {
	c := make([]string, 0, len(s.Validations))
	add := func(format string, v any) { c = append(c, fmt.Sprintf(format, v)) }
	if s.Pattern != "" {
		add("pattern `%s`", s.Pattern)
	}
	if s.Minimum != nil {
		add("minimum %v", *s.Minimum)
	}
	if s.Maximum != nil {
		add("maximum %v", *s.Maximum)
	}
	if s.MinLength != nil {
		add("min length %d", *s.MinLength)
	}
	if s.MaxLength != nil {
		add("max length %d", *s.MaxLength)
	}
	if s.MinItems != nil {
		add("min items %d", *s.MinItems)
	}
	if s.MaxItems != nil {
		add("max items %d", *s.MaxItems)
	}
	for _, v := range s.Validations {
		c = append(c, v.Message)
	}
	return strings.Join(c, "; ")
}

func jsonString(v any) string {
	out, _ := json.Marshal(v)
	return string(out)
}

func contains(list []string, s string) bool {
	for _, x := range list {
		if x == s {
			return true
		}
	}
	return false
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// Flags

type flagDoc struct {
	name, typ, def, usage string
}

var defaultSuffix = regexp.MustCompile(` \(default (.*)\)$`)

// helpFlags runs the package with --help and parses the standard library flag package's usage
// output: "  -name type" followed by "    \t"-indented usage lines ending in " (default x)".
func helpFlags(pkg string) ([]flagDoc, error) {
	cmd := exec.Command("go", "run", pkg, "--help")
	for _, kv := range os.Environ() {
		if !strings.HasPrefix(kv, "PROTEM_") {
			cmd.Env = append(cmd.Env, kv)
		}
	}
	var out bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &out
	runErr := cmd.Run()

	var flags []flagDoc
	var usage []string
	flush := func() {
		if len(flags) == 0 {
			return
		}
		f := &flags[len(flags)-1]
		text := strings.Join(usage, " ")
		if m := defaultSuffix.FindStringSubmatch(text); m != nil {
			f.def = m[1]
			text = strings.TrimSpace(strings.TrimSuffix(text, m[0]))
		}
		f.usage = text
		usage = nil
	}
	for _, line := range strings.Split(out.String(), "\n") {
		switch {
		case strings.HasPrefix(line, "  -"):
			flush()
			head, rest, _ := strings.Cut(strings.TrimPrefix(line, "  -"), "\t")
			name, typ, _ := strings.Cut(head, " ")
			if typ == "" {
				typ = "bool"
			}
			flags = append(flags, flagDoc{name: name, typ: typ})
			if rest != "" {
				usage = append(usage, strings.TrimSpace(rest))
			}
		case strings.HasPrefix(line, "    \t") && len(flags) > 0:
			usage = append(usage, strings.TrimSpace(line))
		}
	}
	flush()
	if len(flags) == 0 {
		return nil, fmt.Errorf("go run %s --help printed no flags (%v):\n%s", pkg, runErr, out.String())
	}
	return flags, nil
}

func flagTable(b *strings.Builder, flags []flagDoc) {
	tableHead(b, "Flag", "Type", "Default", "Description")
	for _, f := range flags {
		row(b, code("--"+f.name), f.typ, code(f.def), cell(f.usage))
	}
}

func operatorFlags() (string, error) {
	flags, err := helpFlags("./cmd")
	if err != nil {
		return "", err
	}
	b := header("Operator flags",
		"Every command-line flag of the operator (the manager binary built from cmd/main.go), with its type, default "+
			"and description. Generated from the binary's --help output.")
	b.WriteString("\nEach flag `--some-name` can also be set with the environment variable `PROTEM_SOME_NAME`: " +
		"`PROTEM_` followed by the flag name in upper case with dashes replaced by underscores. " +
		"A flag given on the command line takes precedence over its environment variable.\n")
	flagTable(b, flags)
	return b.String(), nil
}

func agentFlags() (string, error) {
	flags, err := helpFlags("./cmd/enforcer")
	if err != nil {
		return "", err
	}
	b := header("Agent flags",
		"Every command-line flag of the agent (the binary built from cmd/enforcer/main.go), with its type, default "+
			"and description. Generated from the binary's --help output.")
	b.WriteString("\nThe agent reads its configuration from flags only; it has no environment variable equivalents.\n")
	flagTable(b, flags)
	return b.String(), nil
}

// Chart values

type value struct {
	key, def, description string
}

func chartValues() (string, error) {
	data, err := os.ReadFile("deploy/helm/protem/values.yaml")
	if err != nil {
		return "", err
	}
	var doc yamlv3.Node
	if err := yamlv3.Unmarshal(data, &doc); err != nil {
		return "", err
	}
	if len(doc.Content) != 1 || doc.Content[0].Kind != yamlv3.MappingNode {
		return "", fmt.Errorf("values.yaml is not a mapping")
	}
	var values []value
	if err := collectValues(doc.Content[0], "", &values); err != nil {
		return "", err
	}

	b := header("Chart values",
		"Every value of the protem Helm chart in deploy/helm/protem, with its default and description. Generated "+
			"from the chart's values.yaml and its comments.")
	tableHead(b, "Key", "Default", "Description")
	for _, v := range values {
		row(b, code(v.key), code(v.def), cell(v.description))
	}
	return b.String(), nil
}

// collectValues lists a mapping's keys. A nested mapping whose keys carry no comments of their
// own is one value (e.g. resources); otherwise its keys are listed individually.
func collectValues(m *yamlv3.Node, prefix string, out *[]value) error {
	for i := 0; i+1 < len(m.Content); i += 2 {
		k, v := m.Content[i], m.Content[i+1]
		key := prefix + k.Value
		desc := comment(k.HeadComment, k.LineComment, v.LineComment)
		if v.Kind == yamlv3.MappingNode && len(v.Content) > 0 && hasComments(v) {
			if desc != "" {
				*out = append(*out, value{key: key, description: desc})
			}
			if err := collectValues(v, key+".", out); err != nil {
				return err
			}
			continue
		}
		def := v.Value
		if v.Kind != yamlv3.ScalarNode {
			var x any
			if err := v.Decode(&x); err != nil {
				return fmt.Errorf("%s: %w", key, err)
			}
			def = jsonString(x)
		} else if v.Tag == "!!str" && v.Value == "" {
			def = `""`
		}
		*out = append(*out, value{key: key, def: def, description: desc})
	}
	return nil
}

func hasComments(n *yamlv3.Node) bool {
	if n.HeadComment != "" || n.LineComment != "" {
		return true
	}
	for _, c := range n.Content {
		if hasComments(c) {
			return true
		}
	}
	return false
}

func comment(parts ...string) string {
	var lines []string
	for _, p := range parts {
		for _, l := range strings.Split(p, "\n") {
			if l = strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(l), "#")); l != "" {
				lines = append(lines, l)
			}
		}
	}
	return strings.Join(lines, " ")
}
